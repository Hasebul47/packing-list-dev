"""
Final completed Excel  ->  database   (the GREEN upload box on the router page)
================================================================================
Upload the FINAL, completed packing-list workbooks (the .xlsx you finished in
Excel: yellow cells filled, weights entered ...) and keep them in a SQLite
database so the data is stored and can be searched / re-downloaded later.

Nothing here touches the PO -> packing-list pipelines.

What is stored for every file
  workbooks   one row per uploaded file: name, version, SHA-256, upload time,
              buyer / PO / style / order qty found in the header, counts and
              the ORIGINAL file itself (so it can be downloaded again)
  sheets      one row per sheet: size + the header fields found on it
  sheet_rows  every non-empty row of every sheet, as the values you see in
              Excel (JSON list)

Rules
  * the same file (same SHA-256) is never stored twice
  * the same file NAME with different content is stored as the next version
  * formula cells are stored with the value Excel saved for them. A workbook
    that was generated by a script and never opened in Excel has no saved
    values - the page warns about it (open it in Excel, save, upload again)

Database file:  ./data/packing_list.db   (override with env var PL_DB_PATH)
"""
from __future__ import annotations

import datetime as _dt
import hashlib
import io
import json
import os
import re
import sqlite3
from pathlib import Path

import streamlit as st

import pl_kit as kit                      # STRETCH = width option that works on every Streamlit version

BASE = Path(__file__).resolve().parent
DB_PATH = Path(os.environ.get("PL_DB_PATH") or (BASE / "data" / "packing_list.db"))

MAX_ROWS_PER_SHEET = 20000
MAX_FILE_MB = 50

GREEN = "#16a34a"
GREEN_DARK = "#166534"
GREEN_LIGHT = "#22c55e"

# header label (normalised: upper-case, letters+digits only)  ->  field name
_LABELS = {
    "BUYER": "buyer",
    "LOTNO": "lot_no",
    "STYLE": "style",
    "STYLENO": "style",
    "PONO": "po_no",
    "PONUMBER": "po_no",
    "PO": "po_no",
    "ORDERQTY": "order_qty",
    "COUNTRY": "country",
    "CRD": "crd",
    "DESCRIPTION": "description",
    "EXCESSSHORTQTY": "excess_short_qty",
}

_SCHEMA = """
CREATE TABLE IF NOT EXISTS workbooks (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    file_name       TEXT NOT NULL,
    version         INTEGER NOT NULL DEFAULT 1,
    sha256          TEXT NOT NULL UNIQUE,
    size_bytes      INTEGER NOT NULL,
    uploaded_at     TEXT NOT NULL,
    buyer           TEXT,
    po_no           TEXT,
    style           TEXT,
    order_qty       TEXT,
    sheet_count     INTEGER NOT NULL DEFAULT 0,
    row_count       INTEGER NOT NULL DEFAULT 0,
    formula_cells   INTEGER NOT NULL DEFAULT 0,
    formula_missing INTEGER NOT NULL DEFAULT 0,
    file_blob       BLOB NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_workbooks_name ON workbooks(file_name);
CREATE INDEX IF NOT EXISTS ix_workbooks_po   ON workbooks(po_no);

CREATE TABLE IF NOT EXISTS sheets (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    workbook_id  INTEGER NOT NULL REFERENCES workbooks(id) ON DELETE CASCADE,
    sheet_name   TEXT NOT NULL,
    n_rows       INTEGER NOT NULL DEFAULT 0,
    n_cols       INTEGER NOT NULL DEFAULT 0,
    header_json  TEXT
);
CREATE INDEX IF NOT EXISTS ix_sheets_wb ON sheets(workbook_id);

CREATE TABLE IF NOT EXISTS sheet_rows (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    workbook_id  INTEGER NOT NULL REFERENCES workbooks(id) ON DELETE CASCADE,
    sheet_name   TEXT NOT NULL,
    row_no       INTEGER NOT NULL,
    values_json  TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_rows_wb ON sheet_rows(workbook_id, sheet_name, row_no);
"""


# ============================================================
# Database helpers
# ============================================================
def _connect() -> sqlite3.Connection:
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    con = sqlite3.connect(str(DB_PATH), timeout=30)
    con.execute("PRAGMA foreign_keys = ON")
    con.executescript(_SCHEMA)
    return con


def list_workbooks(search: str = "") -> list[dict]:
    with _connect() as con:
        if search and search.strip():
            term = f"%{search.strip()}%"
            cur = con.execute(
                "SELECT id, file_name, version, uploaded_at, buyer, po_no, style, order_qty, "
                "sheet_count, row_count, formula_missing, size_bytes "
                "FROM workbooks "
                "WHERE file_name LIKE ? OR buyer LIKE ? OR po_no LIKE ? OR style LIKE ? "
                "ORDER BY id DESC",
                (term, term, term, term),
            )
        else:
            cur = con.execute(
                "SELECT id, file_name, version, uploaded_at, buyer, po_no, style, order_qty, "
                "sheet_count, row_count, formula_missing, size_bytes "
                "FROM workbooks ORDER BY id DESC"
            )
        cols = [c[0] for c in cur.description]
        return [dict(zip(cols, r)) for r in cur.fetchall()]


def get_blob(workbook_id: int) -> tuple[str, bytes] | None:
    with _connect() as con:
        r = con.execute("SELECT file_name, file_blob FROM workbooks WHERE id=?",
                        (workbook_id,)).fetchone()
    return (r[0], bytes(r[1])) if r else None


def get_sheet_names(workbook_id: int) -> list[str]:
    with _connect() as con:
        return [r[0] for r in con.execute(
            "SELECT sheet_name FROM sheets WHERE workbook_id=? ORDER BY id", (workbook_id,))]


def get_sheet_rows(workbook_id: int, sheet_name: str) -> list[list]:
    with _connect() as con:
        return [json.loads(r[0]) for r in con.execute(
            "SELECT values_json FROM sheet_rows WHERE workbook_id=? AND sheet_name=? ORDER BY row_no",
            (workbook_id, sheet_name))]


# ============================================================
# Parsing
# ============================================================
def _clean(v):
    """JSON-friendly cell value."""
    if v is None:
        return None
    if isinstance(v, (_dt.datetime, _dt.date, _dt.time)):
        return v.isoformat()
    if isinstance(v, bool):
        return v
    if isinstance(v, (int, float)):
        if isinstance(v, float) and v.is_integer() and abs(v) < 1e15:
            return int(v)
        return v
    s = str(v)
    return s if s.strip() != "" else None


def _norm_label(v) -> str:
    return re.sub(r"[^A-Z0-9]", "", str(v or "").upper())


def _header_fields(rows: list[list]) -> dict:
    """label / value pairs from the top of a sheet (BUYER, LOT NO, P.O NO ...)."""
    found: dict[str, str] = {}
    for row in rows[:25]:
        for i, cell in enumerate(row):
            if not isinstance(cell, str):
                continue
            key = _LABELS.get(_norm_label(cell))
            if not key or key in found:
                continue
            for nxt in row[i + 1:]:
                if nxt is None:
                    continue
                val = str(nxt).strip().lstrip(":：").strip()     # "BUYER | : | GAP" layouts
                if val:
                    found[key] = val
                    break
    return found


def _trim(row: list) -> list:
    while row and row[-1] is None:
        row.pop()
    return row


def parse_workbook(file_name: str, data: bytes) -> dict:
    """Read every sheet. Returns
    {"sheets": [{"name", "rows", "n_cols", "header"}], "formula_cells", "formula_missing"}"""
    ext = Path(file_name).suffix.lower()
    sheets: list[dict] = []
    f_cells = f_missing = 0

    if ext == ".xls":
        import xlrd
        book = xlrd.open_workbook(file_contents=data, formatting_info=False)
        for sh in book.sheets():
            rows = []
            for r in range(min(sh.nrows, MAX_ROWS_PER_SHEET)):
                vals = []
                for c in range(sh.ncols):
                    v = sh.cell_value(r, c)
                    if sh.cell_type(r, c) == xlrd.XL_CELL_DATE and v:
                        try:
                            v = xlrd.xldate_as_datetime(v, book.datemode)
                        except Exception:
                            pass
                    vals.append(_clean(v))
                if any(x is not None for x in vals):
                    rows.append(_trim(vals))
            sheets.append({"name": sh.name, "rows": rows,
                           "n_cols": max((len(r) for r in rows), default=0),
                           "header": _header_fields(rows)})
        return {"sheets": sheets, "formula_cells": 0, "formula_missing": 0}

    import openpyxl
    wb_v = openpyxl.load_workbook(io.BytesIO(data), data_only=True)          # values Excel saved
    wb_f = openpyxl.load_workbook(io.BytesIO(data), data_only=False)         # to count formulas
    for ws_v in wb_v.worksheets:
        ws_f = wb_f[ws_v.title]
        rows = []
        for r_idx, row in enumerate(ws_v.iter_rows(values_only=True), start=1):
            if r_idx > MAX_ROWS_PER_SHEET:
                break
            vals = [_clean(v) for v in row]
            if any(x is not None for x in vals):
                rows.append(_trim(vals))
        for row_f, row_v in zip(ws_f.iter_rows(), ws_v.iter_rows()):
            for cf, cv in zip(row_f, row_v):
                if isinstance(cf.value, str) and cf.value.startswith("="):
                    f_cells += 1
                    if cv.value is None:
                        f_missing += 1
        sheets.append({"name": ws_v.title, "rows": rows,
                       "n_cols": max((len(r) for r in rows), default=0),
                       "header": _header_fields(rows)})
    return {"sheets": sheets, "formula_cells": f_cells, "formula_missing": f_missing}


# ============================================================
# Save
# ============================================================
def save_workbook(file_name: str, data: bytes, parsed: dict | None = None) -> tuple[str, int]:
    """Store one file. Returns ("saved" | "duplicate", workbook_id)."""
    sha = hashlib.sha256(data).hexdigest()
    with _connect() as con:
        r = con.execute("SELECT id FROM workbooks WHERE sha256=?", (sha,)).fetchone()
        if r:
            return "duplicate", int(r[0])

        parsed = parsed or parse_workbook(file_name, data)
        first = {}
        for sh in parsed["sheets"]:
            for k, v in sh["header"].items():
                first.setdefault(k, v)
        version = (con.execute("SELECT COALESCE(MAX(version),0) FROM workbooks WHERE file_name=?",
                               (file_name,)).fetchone()[0]) + 1
        total_rows = sum(len(s["rows"]) for s in parsed["sheets"])

        cur = con.execute(
            "INSERT INTO workbooks (file_name, version, sha256, size_bytes, uploaded_at, buyer, po_no, "
            "style, order_qty, sheet_count, row_count, formula_cells, formula_missing, file_blob) "
            "VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
            (file_name, version, sha, len(data),
             _dt.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
             first.get("buyer"), first.get("po_no"),
             first.get("style") or first.get("lot_no"), first.get("order_qty"),
             len(parsed["sheets"]), total_rows,
             parsed["formula_cells"], parsed["formula_missing"], data),
        )
        wb_id = int(cur.lastrowid)
        for sh in parsed["sheets"]:
            con.execute(
                "INSERT INTO sheets (workbook_id, sheet_name, n_rows, n_cols, header_json) VALUES (?,?,?,?,?)",
                (wb_id, sh["name"], len(sh["rows"]), sh["n_cols"],
                 json.dumps(sh["header"], ensure_ascii=False)))
            con.executemany(
                "INSERT INTO sheet_rows (workbook_id, sheet_name, row_no, values_json) VALUES (?,?,?,?)",
                [(wb_id, sh["name"], i, json.dumps(r, ensure_ascii=False, default=str))
                 for i, r in enumerate(sh["rows"], start=1)])
        return "saved", wb_id


