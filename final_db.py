def uploader_box():
    """The green upload box. Returns the list of uploaded files (maybe empty)."""
    _inject_css()
    with st.container(key="final_db_box"):
        files = st.file_uploader(
            "🟩 FINAL completed XL → database",
            type=["xlsx", "xlsm", "xls"],
            accept_multiple_files=True,
            key="router_final_db",
            help="The finished packing-list Excel files (after you filled the yellow cells). "
                 "They are stored in the database - they do NOT create a new packing list.",
        )
    return files or []


@st.cache_data(show_spinner=False, max_entries=16)
def _parse_cached(file_name: str, data: bytes):
    return parse_workbook(file_name, data)


def render_panel(files, search_query: str = "") -> None:
    """Preview + save button for the uploaded files, and the stored-files browser."""
    search_term = (search_query or "").strip()
    n_stored = 0
    try:
        stored = list_workbooks(search=search_term)
        n_stored = len(stored)
    except Exception as e:                      # e.g. folder not writable
        st.error(f"Database not available: {e}")
        return

    expander_title = (
        f"🗄 Final files → database  ·  {n_stored} found for '{search_term}'"
        if search_term else
        f"🗄 Final files → database  ·  {n_stored} stored"
    )
    with st.expander(expander_title, expanded=bool(files or search_term)):
        if files:
            st.markdown("##### To be saved")
            items = []
            for f in files:
                fname = getattr(f, "name", "Unknown File")
                data = f.getvalue() if hasattr(f, "getvalue") else (f if isinstance(f, (bytes, bytearray)) else b"")
                if len(data) > MAX_FILE_MB * 1024 * 1024:
                    st.error(f"**{fname}** is larger than {MAX_FILE_MB} MB - skipped.")
                    continue
                try:
                    parsed = _parse_cached(fname, bytes(data))
                except Exception as e:
                    st.error(f"**{fname}** could not be read: {e}")
                    continue
                items.append((fname, data, parsed))

            if items:
                preview = []
                for name, data, parsed in items:
                    hdr = {}
                    for sh in parsed["sheets"]:
                        for k, v in sh["header"].items():
                            hdr.setdefault(k, v)
                    preview.append({
                        "File": name,
                        "Sheets": len(parsed["sheets"]),
                        "Rows": sum(len(s["rows"]) for s in parsed["sheets"]),
                        "Buyer": hdr.get("buyer", ""),
                        "PO": hdr.get("po_no", ""),
                        "Style": hdr.get("style") or hdr.get("lot_no", ""),
                    })
                    if parsed["formula_missing"]:
                        st.warning(
                            f"**{name}**: {parsed['formula_missing']} of {parsed['formula_cells']} formula cells "
                            "have no saved value (the file was never opened in Excel). Open it in Excel, "
                            "save it once, then upload it again - otherwise those cells are stored empty.")
                st.dataframe(preview, hide_index=True, **kit.STRETCH)

                if st.button("💾 Save to database", key="final_db_save", type="primary"):
                    saved = dup = 0
                    for name, data, parsed in items:
                        status, _ = save_workbook(name, data, parsed)
                        if status == "saved":
                            saved += 1
                        else:
                            dup += 1
                    if saved:
                        st.success(f"Saved {saved} file(s) to the database.")
                    if dup:
                        st.info(f"{dup} file(s) were already in the database (identical content) - not stored again.")
                    stored = list_workbooks()
                    n_stored = len(stored)

        st.markdown(f"##### Stored files ({n_stored})")
        if not stored:
            st.caption("Nothing stored yet. Upload final completed Excel files in the green box.")
            return

        table = [{
            "ID": r["id"], "File": r["file_name"], "Ver": r["version"],
            "Saved at": r["uploaded_at"], "Buyer": r["buyer"] or "", "PO": r["po_no"] or "",
            "Style": r["style"] or "", "Sheets": r["sheet_count"], "Rows": r["row_count"],
        } for r in stored]
        st.dataframe(table, hide_index=True, **kit.STRETCH)

        labels = {r["id"]: f"#{r['id']} · {r['file_name']} (v{r['version']})" for r in stored}
        pick = st.selectbox("Open a stored file", list(labels), format_func=lambda i: labels[i],
                            key="router_db_pick")
        sheets = get_sheet_names(pick)
        if sheets:
            sheet = st.selectbox("Sheet", sheets, key="router_db_sheet")
            rows = get_sheet_rows(pick, sheet)
            width = max((len(r) for r in rows), default=0)

            def _col(i: int) -> str:
                s = ""
                i += 1
                while i:
                    i, rem = divmod(i - 1, 26)
                    s = chr(65 + rem) + s
                return s

            grid = [{_col(i): ("" if i >= len(r) or r[i] is None else str(r[i])) for i in range(width)} for r in rows]
            st.dataframe(grid, hide_index=True, **kit.STRETCH)
        blob = get_blob(pick)
        if blob:
            st.download_button("⬇ Download the original file", blob[1], file_name=blob[0],
                               key="router_db_download")
